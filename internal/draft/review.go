package draft

import (
	"fmt"
	"strings"
)

// Checklist renders review.md: what a reviewer checks, claim by claim, with
// the facts not found in the cited passages first in each claim.
func Checklist(l *Ledger) string {
	var b strings.Builder
	c := l.Counts()
	fmt.Fprintf(&b, "# Review: %s\n\n", l.Topic)
	fmt.Fprintf(&b, "Generated by %s. %d claims: %d verified, %d unverified, %d needing change, %d rejected; %d without a citation.\n\n",
		l.Generator, c[Verified]+c[Unverified]+c[NeedsChange]+c[Rejected], c[Verified], c[Unverified], c[NeedsChange], c[Rejected], c["uncited"])
	b.WriteString("For each claim, open the cited source and check the statement and every fact listed. Record the result:\n\n")
	b.WriteString("```\ndocsbot draft verify DIR --claim C3 --status verified --by NAME\ndocsbot draft verify DIR --claim C4 --status needs-change --note \"default is 30s, not 60s\"\n```\n\n")
	b.WriteString("Before you mark the page ready:\n\n")
	b.WriteString("- [ ] Every claim is verified, and rejected claims are removed from the draft\n")
	b.WriteString("- [ ] Statements marked **[uncited]** have a source or are removed\n")
	b.WriteString("- [ ] Placeholders are written or removed\n")
	b.WriteString("- [ ] Extractive sentences are rewritten in your own words\n")
	b.WriteString("- [ ] Nothing in the draft comes from material that must not be published\n\n")
	section := "\x00"
	for _, cl := range l.Claims {
		if cl.Removed {
			continue
		}
		if cl.Section != section {
			section = cl.Section
			fmt.Fprintf(&b, "\n## %s\n\n", firstNonEmpty(section, "(no section)"))
		}
		box := " "
		if cl.Status == Verified {
			box = "x"
		}
		text := cl.Text
		if cl.Code {
			text = "code block: `" + strings.ReplaceAll(excerpt(text, 120), "`", "'") + "`"
		}
		fmt.Fprintf(&b, "- [%s] **%s** (%s) %s\n", box, cl.ID, cl.Status, excerpt(text, 300))
		var cites []string
		for _, id := range cl.Citations {
			if s := l.source(id); s != nil {
				cites = append(cites, id+": "+s.Location())
			}
		}
		switch {
		case cl.Uncited && len(cl.Invalid) > 0:
			fmt.Fprintf(&b, "  - **No valid citation**: cites %s, which are not sources\n", strings.Join(cl.Invalid, ", "))
		case cl.Uncited:
			b.WriteString("  - **No citation**: find a source or remove the statement\n")
		default:
			fmt.Fprintf(&b, "  - Sources: %s\n", strings.Join(cites, "; "))
		}
		var missing, found []string
		for _, f := range cl.Facts {
			v := fmt.Sprintf("%s `%s`", f.Kind, strings.ReplaceAll(strings.Join(strings.Split(f.Value, "\n"), "; "), "`", "'"))
			if f.InSource {
				found = append(found, v)
			} else {
				missing = append(missing, v)
			}
		}
		if len(missing) > 0 && !cl.Uncited {
			fmt.Fprintf(&b, "  - **Not found in the cited source, check first**: %s\n", strings.Join(missing, ", "))
		} else if len(missing) > 0 {
			fmt.Fprintf(&b, "  - Facts to check: %s\n", strings.Join(missing, ", "))
		}
		if len(found) > 0 {
			fmt.Fprintf(&b, "  - Facts to check (found in the source): %s\n", strings.Join(found, ", "))
		}
		if cl.Note != "" || cl.Reviewer != "" {
			fmt.Fprintf(&b, "  - Review: %s %s %s\n", cl.Reviewer, cl.Reviewed, cl.Note)
		}
	}
	return b.String()
}
